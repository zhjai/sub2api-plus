package service

import (
	"context"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"github.com/gin-gonic/gin"
	"github.com/stretchr/testify/require"
	"github.com/tidwall/gjson"
)

func TestExcelBPSCompactReturnsActualCompleteWindow(t *testing.T) {
	gin.SetMode(gin.TestMode)
	s := excelBPSTestService(nil)
	tr := &excelBPSFidelityTransport{httpUpstreamRecorder: new(httpUpstreamRecorder)}
	tr.send = func(req *http.Request, raw []byte, attempt int) (*http.Response, error) {
		require.Equal(t, 1, attempt)
		require.Equal(t, "/basispoints/api/responses", req.URL.Path)
		require.Contains(t, string(raw), "compaction_trigger")
		require.Contains(t, string(raw), "KEEP_ALL_ORIGINAL_HISTORY")
		require.NotContains(t, string(raw), "run_officejs")
		return excelBPSMockResponse(200, `data: {"type":"response.completed","response":{"id":"resp_real_compact","model":"gpt-6-astra","status":"completed","output":[{"type":"message","id":"msg_retained","role":"user","content":[{"type":"input_text","text":"RETAINED_TEXT"}]},{"type":"compaction","id":"cmp_real","encrypted_content":"OPAQUE_ORIGINAL_STATE"}],"usage":{"input_tokens":42,"output_tokens":5}}}`+"\n\n"), nil
	}
	s.httpUpstream = tr
	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)
	c.Request = httptest.NewRequest("POST", "/v1/responses/compact", nil)
	result, err := s.Forward(context.Background(), c, excelBPSAccount(t), []byte(`{"model":"gpt-6-astra","input":"KEEP_ALL_ORIGINAL_HISTORY","tools":[{"type":"function","name":"exec","parameters":{"type":"object"}}]}`))
	require.NoError(t, err, rec.Body.String())
	require.Equal(t, 200, rec.Code)
	require.Equal(t, "response.compaction", gjson.Get(rec.Body.String(), "object").String())
	require.Equal(t, "OPAQUE_ORIGINAL_STATE", gjson.Get(rec.Body.String(), "output.1.encrypted_content").String())
	require.Contains(t, rec.Body.String(), "RETAINED_TEXT")
	require.Equal(t, 42, result.Usage.InputTokens)
	require.False(t, strings.Contains(rec.Body.String(), "summary generated by gateway"))
}
